"""Remove only the repository-owned generated output trees.

The direct build keeps every generated byte below three explicit directories --
``out/native`` (MSBuild and vcpkg artifacts and test reports), ``out/reports``
(the source, analysis and diagnostic reports) and ``out/packages`` (release
archives).  ``clean`` removes exactly those and nothing else, so a neighbouring
``out/sol-team`` checkout or any other unrelated directory is preserved.  Every
recursive removal is refused when the target, or anything below it, is a reparse
point, so a link can never redirect the delete outside the repository.
"""

from __future__ import annotations

import argparse
from collections.abc import Sequence
import os
from pathlib import Path
import shutil
import stat


_MODES = ("all", "reports")
_OWNED = {
    "all": ("native", "reports", "packages"),
    "reports": ("reports", "packages"),
}
_REPARSE = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)


class CleanError(RuntimeError):
    """A generated output tree cannot be proven safe to remove."""


def _is_reparse(path: Path) -> bool:
    try:
        information = os.lstat(path)
    except FileNotFoundError:
        return False
    attributes = getattr(information, "st_file_attributes", 0)
    return stat.S_ISLNK(information.st_mode) or bool(attributes & _REPARSE)


def _require_plain_tree(path: Path) -> None:
    """Refuse a reparse point anywhere at or below ``path`` before removal."""

    if _is_reparse(path):
        raise CleanError(f"reparse point is forbidden in generated output: {path}")
    if not path.is_dir():
        return
    for directory, directories, files in path.walk(follow_symlinks=False):
        for name in (*directories, *files):
            child = directory / name
            if _is_reparse(child):
                raise CleanError(f"reparse point is forbidden in generated output: {child}")


def clean(repository: Path | str, mode: str = "all") -> tuple[Path, ...]:
    """Remove every owned output directory for ``mode`` and return what was removed."""

    if mode not in _MODES:
        raise ValueError(f"unsupported clean mode: {mode}")
    out = Path(repository).resolve(strict=True) / "out"
    if not out.is_dir():
        return ()
    if _is_reparse(out):
        raise CleanError(f"reparse point is forbidden in generated output: {out}")
    removed: list[Path] = []
    for name in _OWNED[mode]:
        target = out / name
        if not os.path.lexists(target):
            continue
        _require_plain_tree(target)
        if target.is_dir():
            shutil.rmtree(target)
        else:
            target.unlink()
        removed.append(target)
    return tuple(removed)


def prepare_fresh(directory: Path | str, boundary: Path | str) -> Path:
    """Create an empty ``directory`` under ``boundary``, refusing every hazard.

    The path must stay inside ``boundary`` and no hop from ``boundary`` down to
    the directory, nor anything below it, may be a reparse point.  Only then is
    the previous tree removed and a fresh one created, so a link can never
    redirect the delete outside the owned output root.
    """

    base = Path(os.path.abspath(os.fspath(boundary)))
    target = Path(os.path.abspath(os.fspath(directory)))
    if target != base and base not in target.parents:
        raise CleanError(f"generated output escapes its owned root: {directory}")
    current = target
    while True:
        if _is_reparse(current):
            raise CleanError(f"reparse point is forbidden in generated output: {current}")
        if current == base:
            break
        current = current.parent
    if os.path.lexists(target):
        _require_plain_tree(target)
        shutil.rmtree(target)
    target.mkdir(parents=True)
    return target


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="observer-build clean")
    parser.add_argument("repository", type=Path)
    parser.add_argument("--mode", choices=_MODES, default="all")
    args = parser.parse_args(argv)
    for removed in clean(args.repository, args.mode):
        print(removed)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
